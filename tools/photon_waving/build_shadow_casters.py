"""Build a Photon diagnostic pack that retains only selected distant shadow casters.

Input metadata comes from CasterRegistry after Iris has loaded the source pack.
This is intentionally a clone builder: it never edits the source ZIP or an
installed shader pack.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CLASSES = {"cube": 1, "stairs_slabs": 2}
OFFSETS = {1: 12000, 2: 16000}


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def decode(raw: int) -> tuple[int, int]:
    """Return (original Iris ID, caster class), preserving Iris -1 exactly."""
    if raw == 22000:
        return -1, 1
    if raw == 26000:
        return -1, 2
    if 26000 <= raw <= 26922:
        return raw - 16000, 2
    if 22000 <= raw <= 22922:
        return raw - 12000, 1
    return raw, 0


def in_near_chunks(block_x: float, block_z: float, eye_x: float, eye_z: float) -> bool:
    import math
    return max(abs(math.floor(block_x / 16) - math.floor(eye_x / 16)),
               abs(math.floor(block_z / 16) - math.floor(eye_z / 16))) <= 1


def caster_block_properties(metadata: dict, mode: str) -> str:
    allowed = {"cube"} if mode == "cube" else {"cube", "stairs_slabs"}
    lines = ["", "# Generated by build_shadow_casters.py; complete non-overlapping state mapping."]
    seen: set[str] = set()
    by_target: dict[int, list[str]] = {}
    for group in metadata["groups"]:
        caster_class = group["casterClass"]
        base = int(group["baseId"])
        if caster_class == "none":
            target = base
        elif caster_class in allowed:
            target = int(group["encodedId"])
        elif base == 10000:  # unassigned source state remains unassigned in this mode
            continue
        else:
            target = base
        if not 0 <= target <= 32767:
            raise ValueError(f"unsafe target ID {target}")
        selectors = group["selectors"]
        if not selectors or any("\n" in value for value in selectors):
            raise ValueError("invalid selector metadata")
        for selector in selectors:
            if selector in seen:
                raise ValueError(f"overlapping generated selector: {selector}")
            seen.add(selector)
        by_target.setdefault(target, []).extend(selectors)
    for target, selectors in sorted(by_target.items()):
        lines.append(f"block.{target} = {' '.join(selectors)}")
    return "\n".join(lines) + "\n"


UTILITY_HELPERS = '''
float decode_mc_entity_id(float raw_id) {
    if (raw_id == 22000.0 || raw_id == 26000.0) return -1.0;
    if (raw_id >= 26000.0 && raw_id <= 26922.0) return raw_id - 16000.0;
    if (raw_id >= 22000.0 && raw_id <= 22922.0) return raw_id - 12000.0;
    return raw_id;
}

uint get_caster_class(float raw_id) {
    if (raw_id >= 26000.0 && raw_id <= 26922.0) return 2u;
    if (raw_id >= 22000.0 && raw_id <= 22922.0) return 1u;
    return 0u;
}
'''


def transform(members: dict[str, bytes], mode: str) -> dict[str, bytes]:
    utility_name = "shaders/include/vertex/utility.glsl"
    old_utility = members[utility_name].decode("utf-8")
    if "uint get_material_mask()" not in old_utility:
        raise ValueError("unexpected utility.glsl")
    marker = "uint get_material_mask()"
    old_utility = old_utility.replace("mc_Entity.x", "decode_mc_entity_id(mc_Entity.x)")
    members[utility_name] = old_utility.replace(marker, UTILITY_HELPERS + "\n" + marker, 1).encode("utf-8")

    solid_name = "shaders/program/gbuffers_all_solid.vsh"
    solid = members[solid_name].decode("utf-8")
    old = '''#if defined PROGRAM_GBUFFERS_TERRAIN
    if (mc_Entity.x >= 10901.0 && mc_Entity.x <= 10922.0) {
        mat2 crop_yaw = actually_crop_yaw(pos, at_midBlock, mc_Entity.x);
        tbn[0].xz = crop_yaw * tbn[0].xz;
        tbn[1].xz = crop_yaw * tbn[1].xz;
        tbn[2].xz = crop_yaw * tbn[2].xz;
        pos = animate_actually_crop(pos, at_midBlock, mc_Entity.x);
    } else
#endif'''
    new = '''#if defined PROGRAM_GBUFFERS_TERRAIN
    float original_block_id = decode_mc_entity_id(mc_Entity.x);
    if (original_block_id >= 10901.0 && original_block_id <= 10922.0) {
        mat2 crop_yaw = actually_crop_yaw(pos, at_midBlock, original_block_id);
        tbn[0].xz = crop_yaw * tbn[0].xz;
        tbn[1].xz = crop_yaw * tbn[1].xz;
        tbn[2].xz = crop_yaw * tbn[2].xz;
        pos = animate_actually_crop(pos, at_midBlock, original_block_id);
    } else
#endif'''
    if old not in solid:
        raise ValueError("unexpected gbuffer crop block")
    members[solid_name] = solid.replace(old, new).encode("utf-8")

    shadow_name = "shaders/program/shadow.vsh"
    shadow = members[shadow_name].decode("utf-8")
    shadow = shadow.replace('#include "/include/vertex/displacement.glsl"',
                            '#include "/include/vertex/displacement.glsl"\n#include "/include/vertex/utility.glsl"')
    assignment = re.compile(r"    material_mask = \(mc_Entity\.x >= 10901\.0.*? : uint\(mc_Entity\.x - 10000\.0\);", re.DOTALL)
    def decoded_assignment(match: re.Match[str]) -> str:
        return "    float decoded_mc_entity_id = decode_mc_entity_id(mc_Entity.x);\n" + match.group(0).replace("mc_Entity.x", "decoded_mc_entity_id")
    shadow, count = assignment.subn(decoded_assignment, shadow, count=1)
    if count != 1:
        raise ValueError("unexpected shadow material assignment")
    old_crop = '''    if (mc_Entity.x >= 10901.0 && mc_Entity.x <= 10922.0) {
        pos = animate_actually_crop(pos, at_midBlock, mc_Entity.x);
    } else {'''
    new_crop = '''    float original_block_id = decoded_mc_entity_id;
    uint caster_class = get_caster_class(mc_Entity.x);
    vec3 owning_block_center = floor(pos + at_midBlock * (1.0 / 64.0)) + 0.5;
    ivec2 caster_chunk = ivec2(floor(owning_block_center.xz * (1.0 / 16.0)));
    ivec2 eye_chunk = ivec2(floor(eyePosition.xz * (1.0 / 16.0)));
    bool near_caster = all(lessThanEqual(abs(caster_chunk - eye_chunk), ivec2(1)));
    if (!near_caster && caster_class == 0u) {
        // All vertices of a rejected block use the same off-frustum point.
        gl_Position = vec4(2.0, 2.0, 2.0, 1.0);
        return;
    }
    if (original_block_id >= 10901.0 && original_block_id <= 10922.0) {
        pos = animate_actually_crop(pos, at_midBlock, original_block_id);
    } else {'''
    if old_crop not in shadow:
        raise ValueError("unexpected shadow crop block")
    members[shadow_name] = shadow.replace(old_crop, new_crop).encode("utf-8")

    for name in ("shaders/program/voxy_opaque.glsl", "shaders/program/voxy_translucent.glsl"):
        text = members[name].decode("utf-8")
        old = "uint material_mask = max(parameters.customId - 10000u, 0u);"
        new = "uint voxy_raw_id = parameters.customId;\n    uint voxy_original_id = (voxy_raw_id >= 26000u && voxy_raw_id <= 26922u) ? voxy_raw_id - 16000u : ((voxy_raw_id >= 22000u && voxy_raw_id <= 22922u) ? voxy_raw_id - 12000u : voxy_raw_id);\n    voxy_original_id = (voxy_original_id == 10000u && voxy_raw_id >= 22000u && voxy_raw_id <= 26922u) ? uint(-1) : voxy_original_id;\n    uint material_mask = max(voxy_original_id - 10000u, 0u);"
        if old not in text:
            raise ValueError(f"unexpected Voxy material assignment: {name}")
        members[name] = text.replace(old, new).encode("utf-8")
    return members


def replace_block_assignments(source_properties: str, generated: str) -> str:
    """Remove complete block.<id> logical assignments, retaining directives/layers."""
    kept: list[str] = []
    skipping = False
    for line in source_properties.splitlines():
        if skipping:
            skipping = line.rstrip().endswith("\\")
            continue
        if line.lstrip().startswith("block."):
            skipping = line.rstrip().endswith("\\")
            continue
        kept.append(line)
    return "\n".join(kept) + generated


def build(source: Path, metadata_path: Path, output: Path, mode: str) -> dict:
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    if metadata.get("cubeOffset") != 12000 or metadata.get("stairsSlabsOffset") != 16000:
        raise ValueError("unsupported registry encoding")
    if any(not row.get("passed") for row in metadata.get("assertions", [])):
        raise ValueError("registry assertions did not pass")
    with zipfile.ZipFile(source) as archive:
        members = {info.filename: archive.read(info.filename) for info in archive.infolist()}
        original = dict(members)
        infos = {info.filename: info for info in archive.infolist()}
    for required in ("shaders/block.properties", "shaders/include/vertex/utility.glsl", "shaders/program/shadow.vsh"):
        if required not in members:
            raise ValueError(f"source pack missing {required}")
    source_properties = members["shaders/block.properties"].decode("utf-8")
    members["shaders/block.properties"] = replace_block_assignments(source_properties, caster_block_properties(metadata, mode)).encode("utf-8")
    members = transform(members, mode)
    changed = sorted(name for name, data in members.items() if data != original[name])
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, data in members.items():
            archive.writestr(infos[name], data)
    return {"source": str(source), "source_sha256": sha(source), "metadata": str(metadata_path),
            "metadata_sha256": sha(metadata_path), "output": str(output), "mode": mode,
            "changed_members": changed,
            "entity_blockentity_policy": "entity shadow program retains source behavior; shadow_block shares the filtered non-entity path; benchmark contains no block entities"}


def self_test() -> None:
    for base in range(10001, 10923):
        assert decode(base) == (base, 0)
        assert decode(base + 12000) == (base, 1)
        assert decode(base + 16000) == (base, 2)
    assert decode(22001) == (10001, 1)
    assert decode(26922) == (10922, 2)
    assert decode(-1) == (-1, 0)
    assert decode(22000) == (-1, 1)
    assert decode(26000) == (-1, 2)
    assert decode(10080) == (10080, 0)
    assert in_near_chunks(-16.0, -16.0, -0.01, -0.01)
    assert not in_near_chunks(-48.0, 0.0, -0.01, 0.0)
    assert in_near_chunks(31.999, 31.999, 0.0, 0.0)
    assert not in_near_chunks(32.0, 0.0, 0.0, 0.0)
    sample = {"groups": [{"baseId": 10001, "casterClass": "cube", "encodedId": 22001, "selectors": ["minecraft:stone"]},
                         {"baseId": 10001, "casterClass": "stairs_slabs", "encodedId": 26001, "selectors": ["minecraft:oak_slab"]},
                         {"baseId": 10002, "casterClass": "none", "encodedId": 10002, "selectors": ["minecraft:wheat"]}]}
    assert "block.22001" in caster_block_properties(sample, "cube")
    assert "block.26001" not in caster_block_properties(sample, "cube")
    assert "block.26001" in caster_block_properties(sample, "cube-stairs-slabs")
    assert "block.10002" in caster_block_properties(sample, "cube")
    duplicate = {"groups": [sample["groups"][0], {"baseId": 10001, "casterClass": "none", "encodedId": 10001, "selectors": ["minecraft:stone"]}]}
    try:
        caster_block_properties(duplicate, "cube")
        raise AssertionError("overlap was accepted")
    except ValueError:
        pass
    merged = {"groups": [{"baseId": 10001, "casterClass": "none", "encodedId": 10001, "selectors": ["minecraft:wheat"]},
                           {"baseId": 10001, "casterClass": "stairs_slabs", "encodedId": 26001, "selectors": ["minecraft:oak_slab"]}]}
    rendered = caster_block_properties(merged, "cube")
    assert rendered.count("block.10001 =") == 1 and "minecraft:wheat minecraft:oak_slab" in rendered
    multiline = "# keep\nblock.1 = minecraft:a \\\n+ minecraft:b\nlayer.solid=minecraft:stone\nblock.2=minecraft:c\n"
    stripped = replace_block_assignments(multiline, "block.7 = minecraft:stone\n")
    assert "minecraft:a" not in stripped and "minecraft:b" not in stripped and "layer.solid" in stripped


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path)
    parser.add_argument("--metadata", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--mode", choices=("cube", "cube-stairs-slabs"))
    parser.add_argument("--report", type=Path)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        self_test(); print("PASS")
        return
    if not all((args.source, args.metadata, args.output, args.mode, args.report)):
        parser.error("source, metadata, output, mode and report are required")
    report = build(args.source, args.metadata, args.output, args.mode)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
